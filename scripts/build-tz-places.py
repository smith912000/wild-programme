"""Writes the time-zone place table into assets/wild-time.js (between the TZ-PLACES markers).

Every IANA time zone in tzdata's zone.tab, with the coordinates of its principal city, rounded to
0.1 degree (about 10 km, under a minute of sunrise). Old names that browsers may still report
(Asia/Calcutta, Europe/Kiev, US/Eastern and the like) point at their current zone.
Run: python3 scripts/build-tz-places.py [/usr/share/zoneinfo]
"""
import os, re, sys

zi = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'

def deg(s, w):
    sign = -1 if s[0] == '-' else 1
    s = s[1:]
    d, m, sec = int(s[:w]), int(s[w:w + 2]), int(s[w + 2:w + 4] or 0)
    return sign * (d + m / 60 + sec / 3600)

zones = {}
for line in open(os.path.join(zi, 'zone.tab')):
    if line.startswith('#') or not line.strip():
        continue
    cc, coord, name = line.split('\t')[:3]
    m = re.match(r'([+-]\d+)([+-]\d+)$', coord)
    la, lo = m.group(1), m.group(2)
    zones[name.strip()] = (round(deg(la, 2), 1), round(deg(lo, 3), 1))

links = {}
for line in open(os.path.join(zi, 'tzdata.zi')):
    if line.startswith('L '):
        _, target, alias = line.split()
        if target in zones and '/' in alias and not alias.startswith('Etc/'):
            links[alias] = target

def num(x):
    s = ('%.1f' % x).rstrip('0').rstrip('.')
    return s.replace('0.', '.') if s.startswith('0.') else s.replace('-0.', '-.')

# grouped by area so the area name is written once: Area: "City lat lon,City lat lon"
areas = {}
for name in sorted(zones):
    area, city = name.split('/', 1)
    la, lo = zones[name]
    areas.setdefault(area, []).append('%s %s %s' % (city, num(la), num(lo)))
places = ',\n    '.join("%s: '%s'" % (a, ','.join(v)) for a, v in sorted(areas.items()))
alias = ','.join('%s=%s' % (a, t) for a, t in sorted(links.items()))

block = ("  /* TZ-PLACES (generated by scripts/build-tz-places.py from tzdata zone.tab; do not edit by hand).\n"
         "     Every IANA time zone and the place its clock is set by, so the sunrise and planetary hours are\n"
         "     the visitor's own. %d zones, %d old names. */\n"
         "  var TZP = {\n    %s\n  };\n"
         "  var TZA = '%s';\n"
         "  /* /TZ-PLACES */") % (len(zones), len(links), places, alias)

p = os.path.join(os.path.dirname(__file__), '..', 'assets', 'wild-time.js')
s = open(p, encoding='utf-8').read()
s2 = re.sub(r'  /\* TZ-PLACES .*?/\* /TZ-PLACES \*/', lambda m: block, s, flags=re.S)
if s2 == s and 'TZ-PLACES' not in s:
    raise SystemExit('markers not found')
open(p, 'w', encoding='utf-8').write(s2)
print('zones', len(zones), 'aliases', len(links))
